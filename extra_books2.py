    os.makedirs("data/processed", exist_ok=True)
    with open(out, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["ISBN","Book-Title","Book-Author","Year-Of-Publication","Publisher","Category","douban_rating","rating_count","Language","description"])
        w.writeheader()
        w.writerows(rows)
