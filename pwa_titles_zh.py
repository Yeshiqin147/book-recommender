"""英文书名 -> 中文译名 映射表。
key 使用规范化的主标题（去掉括号注释、冒号副标题、常见尾缀）。
用于跨语言检索：搜索中文也能命中英文书。
"""
import re


def norm_en_title(t):
    """把英文书名规范化为可查 key。"""
    t = str(t)
    t = t.replace("&amp;", "&")
    # 迭代去除括号（支持嵌套括号，如 "(Harry Potter (Paperback))"）
    while "(" in t and ")" in t:
        t = re.sub(r"\([^()]*\)", " ", t)
    t = re.sub(r":.*$", "", t)          # 去掉冒号后的副标题
    t = re.sub(r"\s+", " ", t).strip()
    t = re.sub(r"\s+A Novel$", "", t)
    t = re.sub(r"\s+A Memoir$", "", t)
    return t


