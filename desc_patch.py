patched, tpl_added, kept = 0, 0, 0
for b in books:
    if b['lang'] != 'cn':
        continue
    title = b['title']
    if title in PATCH:
        b['desc'] = PATCH[title]
        patched += 1
    else:
        desc = (b.get('desc') or '').strip()
        sc = b.get('subcat', '')
        if len(desc) < 45 and sc in TPL:
            b['desc'] = desc.rstrip('。') + '。' + TPL[sc]
            tpl_added += 1
        else:
            kept += 1

cn = [b for b in books if b['lang']=='cn']
dl = [len(b['desc']) for b in cn]
with_desc = sum(1 for b in books if (b.get('desc') or '').strip())
d['meta'] = {'total': len(books),
             'en': sum(1 for b in books if b['lang']=='en'),
             'cn': len(cn), 'with_desc': with_desc}
